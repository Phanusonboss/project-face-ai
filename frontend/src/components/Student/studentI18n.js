function getPath(obj, path) {
  return path.split(".").reduce((acc, k) => (acc && acc[k] !== undefined ? acc[k] : undefined), obj);
}

export function translateStudent(language, key, vars) {
  let value = getPath(studentTranslations[language], key);
  if (value === undefined) value = getPath(studentTranslations.th, key);
  if (value === undefined) return key;
  if (typeof value !== "string" || !vars) return value;
  return value.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? vars[name] : m));
}

const LOCALES = { th: "th-TH", en: "en-GB" };

/**
 * ข้อความ + รูปแบบวันที่ตามภาษาที่เลือก สำหรับหน้าฝั่งนักศึกษา
 *   const { t, date, locale } = useStudentI18n();
 *   t("dashboard.lateThisMonth", { n: 2 })
 *   date("2026-10-05")  -> "5 ต.ค. 2569" / "5 Oct 2026"
 */
export function useStudentI18n() {
  const { language } = useAppearanceSettings();
  const locale = LOCALES[language] || LOCALES.th;

  const t = useCallback((key, vars) => translateStudent(language, key, vars), [language]);

  const date = useCallback(
    (iso, opts = { day: "numeric", month: "short", year: "numeric" }) =>
      iso ? parseDate(iso).toLocaleDateString(locale, opts) : "-",
    [locale]
  );

  return { t, date, locale, language };
}
